SCANS: list = []
LAUNCHED: list = []


def fake_start_menu():
    SCANS.append(1)
    return [dict(a) for a in START_MENU]


def setup():
    apps.SOURCE = fake_start_menu
    apps.LAUNCH = lambda app: LAUNCHED.append(app["name"])
    apps.reset()
    SCANS.clear()
    LAUNCHED.clear()
    LLM_REPLIES.clear()
    PROMPTS.clear()


def say(text, reply=None, source="typed"):
    if reply is not None:
        LLM_REPLIES.append(reply)
    return asyncio.run(conversation.converse(text, source=source))


def opened(name):
    return {"say": "On it!", "mood": "happy", "action": {"type": "open_app", "name": name}}


# ------------------------------------------------------------------ matching

def test_names_people_say_find_the_app():
    setup()
    cases = {
        "vs code": "Visual Studio Code", "VS Code": "Visual Studio Code", "chrome": "Google Chrome",
        "whats app": "WhatsApp", "spider man": "Marvel’s Spider-Man Remastered", "powershell": "Windows PowerShell",
        "notes": "Sticky Notes", "microsoft word": "Word", "the word app": "Word", "files": "File Explorer",
        "pycharm": "PyCharm 2025.2.4", "visual studio cold": "Visual Studio Code",  # misheard
    }
    for asked, want in cases.items():
        got = apps.find(asked)
        assert got and got["name"] == want, (asked, got)


def test_things_that_arent_apps_are_never_found():
    setup()
    for asked in ["uninstall node", "delete all tap virtual ethernet adapters", "reset preferences",
                  "steam support center", "release notes", "run me"]:
        got = apps.find(asked)
        assert got is None, (asked, got)
    names = {a["name"] for a in apps.installed()}
    assert "Uninstall Node.js" not in names and "Run me" not in names and "Marvel’s Spider-Man Remastered" in names


def test_no_wild_guesses():
    setup()
    assert apps.find("spotify") is None
    assert apps.find("teams") is None  # not "Steam"
    assert apps.find("the door") is None


def test_websites_are_not_opened_as_apps_without_the_model():
    setup()
    assert apps.strong_match("google") is None  # would otherwise be Google Chrome
    assert apps.strong_match("youtube") is None
    assert apps.strong_match("chrome")["name"] == "Google Chrome"


# ------------------------------------------------------------- conversation

def test_the_model_can_open_an_app():
    setup()
    r = say("start visual studio code", opened("Visual Studio Code"))
    assert LAUNCHED == ["Visual Studio Code"], LAUNCHED
    assert r["say"] == "Opening Visual Studio Code.", r
    assert r["move"] == "nod" and not r["applied"] and not r["follow_up"], r
    assert r["action"] == {"type": "open_app", "name": "Visual Studio Code"}, r


def test_open_x_needs_no_model():
    setup()
    r = say("open chrome")
    assert LAUNCHED == ["Google Chrome"] and r["say"] == "Opening Google Chrome.", (LAUNCHED, r)
    r = say("Hey Bit, launch whats app please", source="voice")
    assert LAUNCHED == ["Google Chrome", "WhatsApp"], LAUNCHED
    assert PROMPTS == [], "the model was asked"


def test_open_something_else_goes_to_the_model():
    setup()
    r = say("open google", {"say": "", "mood": "happy", "action": {"type": "search", "query": "google", "open": True}})
    assert LAUNCHED == [] and r["open_url"], r
    r = say("open my reminders", {"say": "You've got nothing today.", "mood": "happy", "action": None})
    assert LAUNCHED == [] and LLM_REPLIES == [], r


def test_an_app_that_isnt_installed_says_so_after_one_fresh_look():
    setup()
    apps.installed()
    apps._cache["at"] -= apps.RESCAN_AFTER_S + 1  # the list is a while old
    r = say("open spotify", opened("Spotify"))
    assert LAUNCHED == [] and "couldn't find an app called \"Spotify\"" in r["say"], r
    assert len(SCANS) == 2, "should read the Start menu again once (just installed?)"
    assert r["move"] is None and not r["action"], r


def test_launch_failure_says_so():
    setup()

    def broken(app):
        raise OSError("nope")

    apps.LAUNCH = broken
    r = say("open word")
    assert r["say"] == "I couldn't open Word, sorry.", r


def test_the_app_list_never_reaches_the_model():
    setup()
    memory.new_thread()  # a fresh chat: earlier tests' "Opening ..." replies aren't in its history
    apps.installed()  # the list is loaded...
    say("what's up?", {"say": "Not much!", "mood": "happy", "action": None})
    say("start steam", opened("Steam"))
    assert LAUNCHED == ["Steam"] and len(PROMPTS) == 2, (LAUNCHED, len(PROMPTS))
    for prompt in PROMPTS:  # ...but apps nobody mentioned never show up in what the model sees
        for name in ("Google Chrome", "PyCharm", "Spider-Man", "Sticky Notes", "PowerShell"):  # (not the prompt's examples)
            assert name not in prompt, name


