def test_starts_apps_the_way_the_start_menu_does():
    calls = []
    real = subprocess.Popen
    subprocess.Popen = lambda args, **kw: calls.append(args)
    try:
        apps._launch({"name": "Visual Studio Code", "id": "Microsoft.VisualStudioCode"})
        apps._launch({"name": "Spider-Man", "id": "steam://rungameid/1817070"})
    finally:
        subprocess.Popen = real
    assert calls == [["explorer.exe", "shell:AppsFolder\\Microsoft.VisualStudioCode"], ["explorer.exe", "steam://rungameid/1817070"]], calls


def test_dry_run_starts_nothing():
    calls = []
    real = subprocess.Popen
    subprocess.Popen = lambda args, **kw: calls.append(args)
    os.environ["REMINDER_APPS_DRY_RUN"] = "1"
    try:
        apps._launch({"name": "Visual Studio Code", "id": "Microsoft.VisualStudioCode"})
    finally:
        subprocess.Popen = real
        del os.environ["REMINDER_APPS_DRY_RUN"]
    assert calls == [], calls


def test_reads_the_start_menu_from_powershell():
    class Done:
        def __init__(self, out):
            self.stdout = out.encode("utf-8")

    real = subprocess.run
    try:
        subprocess.run = lambda *a, **kw: Done(json.dumps([{"Name": "Marvel’s Spider-Man", "AppID": "steam://rungameid/1"}, {"Name": "Paint", "AppID": "Microsoft.Paint_8wekyb3d8bbwe!App"}]))
        assert apps._scan() == [{"name": "Marvel’s Spider-Man", "id": "steam://rungameid/1"}, {"name": "Paint", "id": "Microsoft.Paint_8wekyb3d8bbwe!App"}]
        subprocess.run = lambda *a, **kw: Done(json.dumps({"Name": "Paint", "AppID": "Microsoft.Paint_8wekyb3d8bbwe!App"}))
        assert apps._scan() == [{"name": "Paint", "id": "Microsoft.Paint_8wekyb3d8bbwe!App"}]  # a lone app
    finally:
        subprocess.run = real


def test_a_broken_start_menu_scan_never_breaks_a_turn():
    setup()

    def broken():
        raise subprocess.TimeoutExpired("powershell", 15)

    apps.SOURCE = broken
    apps.reset()
    r = say("open chrome", {"say": "Hmm.", "mood": "curious", "action": {"type": "open_app", "name": "Google Chrome"}})
    assert LAUNCHED == [] and "couldn't find" in r["say"], r


